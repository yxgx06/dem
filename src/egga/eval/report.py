from __future__ import annotations

import json

import pandas as pd

from egga.config import REPO_ROOT, load_config
from egga.eval.stress import RESULTS_DIR

DOCS = REPO_ROOT / "docs"
CONTROLLER_ORDER = ["pid", "pd_ff", "rl_handtyped", "rl_trained"]


def _cell(group: pd.DataFrame) -> str:
    n = len(group)
    n_div = int(group["diverged"].sum())
    if n == 1:
        row = group.iloc[0]
        return "DIV" if row["diverged"] else f"{row['max_abs_ey_cm']:.2f}"
    if n_div == n:
        return f"DIV ({n_div}/{n})"
    median = group[~group["diverged"]]["max_abs_ey_cm"].median()
    return f"{n_div}/{n} DIV, median {median:.2f}" if n_div else f"median {median:.2f}"


def stress_table(summary: pd.DataFrame) -> str:
    lines = [
        "| case | " + " | ".join(CONTROLLER_ORDER) + " |",
        "|---|" + "---|" * len(CONTROLLER_ORDER),
    ]
    for case in summary["case"].drop_duplicates():
        sub = summary[summary["case"] == case]
        cells = [_cell(sub[sub["controller"] == c]) for c in CONTROLLER_ORDER]
        lines.append(f"| {case} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def discrepancy_table(summary: pd.DataFrame) -> tuple[str, int]:
    ref = load_config("audit_reference.yaml")
    tol = float(ref["tolerance_cm"])
    lines = [
        "| case | controller | audit claim | measured (seed 0) | status |",
        "|---|---|---|---|---|",
    ]
    flagged = 0
    for case, claims in ref["cases"].items():
        for ctrl, claim in claims.items():
            mask = (
                (summary["case"] == case)
                & (summary["controller"] == ctrl)
                & (summary["seed"] == 0)
            )
            row = summary[mask].iloc[0]
            measured = "DIV" if row["diverged"] else f"{row['max_abs_ey_cm']:.2f}"
            if claim == "DIV" or row["diverged"]:
                ok = (claim == "DIV") == bool(row["diverged"])
            else:
                ok = abs(float(claim) - float(row["max_abs_ey_cm"])) <= tol
            flagged += 0 if ok else 1
            status = "agrees" if ok else "DIFFERS"
            lines.append(f"| {case} | {ctrl} | {claim} | {measured} | {status} |")
    return "\n".join(lines), flagged


def matlab_table() -> str:
    golden = json.loads((RESULTS_DIR / "matlab_golden.json").read_text(encoding="utf-8"))
    summary = pd.read_parquet(RESULTS_DIR / "summary.parquet")
    nominal = summary[(summary["case"] == "nominal") & (summary["seed"] == 0)]
    lines = [
        f"MATLAB version: {golden['matlab_version']}",
        "",
        "| controller | MATLAB max cm | Python max cm | MATLAB RMS cm | Python RMS cm |",
        "|---|---|---|---|---|",
    ]
    for ctrl in ("pid", "pd_ff", "rl_handtyped"):
        row = nominal[nominal["controller"] == ctrl].iloc[0]
        g = golden[ctrl]
        lines.append(
            f"| {ctrl} | {g['max_abs_ey_cm']:.2f} | {row['max_abs_ey_cm']:.2f} | "
            f"{g['rms_ey_cm']:.2f} | {row['rms_ey_cm']:.2f} |"
        )
    return "\n".join(lines)


def main() -> None:
    summary = pd.read_parquet(RESULTS_DIR / "summary.parquet")
    meta = summary.iloc[0]
    header = (
        f"Status: MEASURED. Generated by `python -m egga.eval.report` from "
        f"`results/phase0/summary.parquet` (git {meta['git_sha'][:8]}, "
        f"config hash {meta['config_hash']}, dirty={bool(meta['git_dirty'])}).\n"
    )
    DOCS.mkdir(exist_ok=True)
    table = (
        "# Phase 0 stress table\n\n" + header
        + "\nMax cross-track error in cm over the 75 s mission; DIV = |e_y| exceeded "
        "the divergence threshold or went non-finite. Noise case aggregates 10 seeds.\n\n"
        + stress_table(summary) + "\n"
    )
    (DOCS / "phase0_table.md").write_text(table, encoding="utf-8")

    disc, flagged = discrepancy_table(summary)
    report = (
        "# Phase 0 discrepancies against the audit\n\n" + header
        + "\nThe audit numbers come from `legacy/lib3.py`, a separate Python port. They are "
        "claims taken from `configs/audit_reference.yaml`, not results of this repo. "
        f"{flagged} cell(s) differ by more than the tolerance or in divergence status.\n\n"
        + disc + "\n\n## MATLAB cross-check (nominal)\n\n" + matlab_table() + "\n"
    )
    (DOCS / "phase0_discrepancies.md").write_text(report, encoding="utf-8")
    print(f"wrote docs/phase0_table.md and docs/phase0_discrepancies.md; {flagged} differing cells")


if __name__ == "__main__":
    main()
