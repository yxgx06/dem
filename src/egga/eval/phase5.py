from __future__ import annotations

from typing import Any

import pandas as pd

from egga.config import REPO_ROOT
from egga.eval.baselines import evaluate_set
from egga.eval.metrics2 import MODE_NAMES
from egga.eval.provenance import provenance

RESULTS_DIR = REPO_ROOT / "results" / "phase5"
DOCS = REPO_ROOT / "docs"
CONTROLLERS = ("b0_pid_ff", "b1_pd_ff", "b7_lqr_true_mass", "b4_supervised")
EVAL_SETS = ("train", "val")
BIG_ERROR_CM = 50.0


def aggregate(df: pd.DataFrame) -> pd.DataFrame:
    rows: list[dict[str, Any]] = []
    for ctrl in CONTROLLERS:
        sub = df[df["controller"] == ctrl]
        ok = sub[~sub["diverged"]]
        rows.append(
            {
                "controller": ctrl,
                "n": len(sub),
                "diverged": int(sub["diverged"].sum()),
                "median_max_cm": float(ok["max_abs_ey_cm"].median()),
                "p95_of_max_cm": float(ok["max_abs_ey_cm"].quantile(0.95)),
                "mean_rms_cm": float(ok["rms_ey_cm"].mean()),
                "median_progress": float(sub["progress_fraction"].median()),
                "mean_speed_mps": float(sub["mean_speed_mps"].mean()),
                "utilisation_over_frac": float(sub["utilisation_over_frac"].mean()),
            }
        )
    return pd.DataFrame(rows)


def mode_table(df: pd.DataFrame) -> pd.DataFrame:
    sub = df[df["controller"] == "b4_supervised"]
    return pd.DataFrame(
        [{"mode": name, "mean_fraction": float(sub[f"mode_{name}"].mean())} for name in MODE_NAMES]
    )


def paired_table(df: pd.DataFrame) -> pd.DataFrame:
    """B4 against each other controller, scenario by scenario."""
    b4 = df[df["controller"] == "b4_supervised"].set_index("scenario")
    rows = []
    for ctrl in CONTROLLERS[:-1]:
        other = df[df["controller"] == ctrl].set_index("scenario").loc[b4.index]
        failed_other = other["diverged"] | (other["max_abs_ey_cm"] > BIG_ERROR_CM)
        failed_b4 = b4["diverged"] | (b4["max_abs_ey_cm"] > BIG_ERROR_CM)
        rows.append(
            {
                "vs": ctrl,
                "scenarios": len(b4),
                "other_failed_b4_ok": int((failed_other & ~failed_b4).sum()),
                "b4_failed_other_ok": int((failed_b4 & ~failed_other).sum()),
                "both_failed": int((failed_b4 & failed_other).sum()),
                "b4_progress_over_other": float(
                    (b4["progress_fraction"] / other["progress_fraction"].clip(lower=1e-6)).median()
                ),
            }
        )
    return pd.DataFrame(rows)


def _md(df: pd.DataFrame, floats: int = 3) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for row in df.itertuples(index=False):
        cells = [f"{v:.{floats}f}" if isinstance(v, float) else str(v) for v in row]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def main() -> None:
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    DOCS.mkdir(exist_ok=True)
    meta = provenance()
    sections = []
    for set_name in EVAL_SETS:
        df = evaluate_set(CONTROLLERS, set_name)
        df.to_parquet(RESULTS_DIR / f"{set_name}_runs.parquet", index=False)
        agg, paired, modes = aggregate(df), paired_table(df), mode_table(df)
        sections.append(
            f"## {set_name} set ({df['scenario'].nunique()} scenarios)\n\n"
            + _md(agg)
            + "\n\nB4 against each controller (failure = diverged or max error > "
            + f"{BIG_ERROR_CM:g} cm):\n\n"
            + _md(paired)
            + "\n\nB4 time in each supervisor mode (mean fraction of ticks):\n\n"
            + _md(modes)
        )
    text = (
        "# Phase 5 supervisor: B4 (classical gains + supervisor)\n\n"
        f"Status: MEASURED. Generated by `python -m egga.eval.phase5` (git {meta['git_sha'][:8]}, "
        f"config hash {meta['config_hash']}, dirty={meta['git_dirty']}). B4 is the tuned B0 "
        "structure with gains projected onto the verified envelope, speed set by the supervisor "
        "(friction speed cap and verified speed) and the envelope guard on the steering command; "
        "it uses the Phase 3 estimators (no oracle). B0/B1/B7 run at the planned speed with "
        "oracle friction. `progress` is the fraction of the planned route covered in the "
        "scenario time, the cost of the supervisor's caution.\n\n" + "\n\n".join(sections) + "\n"
    )
    (DOCS / "phase5_report.md").write_text(text, encoding="utf-8")
    print("wrote docs/phase5_report.md")


if __name__ == "__main__":
    main()
